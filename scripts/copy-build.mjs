// Copy the Vite build in dist/ to a folder GitHub Pages can serve directly
// (the repo root by default, or the folder given as the first argument).
// Only index.html, assets/ and .nojekyll in that folder are replaced.
import { cpSync, existsSync, readFileSync, rmSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const dist = join(root, 'dist');
const target = resolve(root, process.argv[2] ?? '.');

if (!existsSync(join(dist, 'index.html'))) {
  console.error('dist/index.html not found. Run "vite build" first.');
  process.exit(1);
}

mkdirSync(target, { recursive: true });
rmSync(join(target, 'assets'), { recursive: true, force: true });
cpSync(join(dist, 'assets'), join(target, 'assets'), { recursive: true });

const note =
  '<!-- Built file: generated by "npm run build" from src/index.html. Edit src/ instead. -->\n';
const html = readFileSync(join(dist, 'index.html'), 'utf8');
writeFileSync(join(target, 'index.html'), html.replace(/^(<!doctype html>\n?)/i, `$1${note}`));

// Serve files as-is (skip Jekyll processing on GitHub Pages)
writeFileSync(join(target, '.nojekyll'), '');

console.log(`Copied the built site to ${target === root ? 'the repo root' : target}`);
